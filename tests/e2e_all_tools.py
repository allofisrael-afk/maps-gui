def sha(path):  # T24: content hash, or None when the file does not exist
    if not os.path.exists(path):  # T24: no user file is a valid state too
        return None  # T24: nothing to compare
    with open(path, "rb") as f:  # T24: hash raw bytes so formatting changes count as changes
        return hashlib.sha256(f.read()).hexdigest()  # T24: stable fingerprint


def port_busy(port):  # T24: True when something already listens on localhost:port
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:  # T24: plain TCP probe
        s.settimeout(0.5)  # T24: do not hang on a firewall
        return s.connect_ex(("127.0.0.1", port)) == 0  # T24: 0 = connection accepted = busy


