# מיון מהארוך לקצר לפי מספר תווים בביטוי — מבטיח שביטויים רב-מיליים
# ייבדקו לפני תת-הביטויים/המילים הבודדות שלהם.
_ABBREVIATIONS.sort(key=lambda pair: len(pair[0]), reverse=True)

_LOOKUP = dict(_ABBREVIATIONS)

_ABBR_RE = re.compile(
    r"\b(" + "|".join(re.escape(phrase) for phrase, _he in _ABBREVIATIONS) + r")\b",
    re.IGNORECASE,
)


def render_hebrew_gloss(text: str) -> str:
    """מחזיר תרגום גס לעברית של טקסט NOTAM — תמיד להציג לצד המקור האנגלי, לא במקומו."""
    if not text:
        return ""

    def _replace(match: "re.Match[str]") -> str:
        return _LOOKUP.get(match.group(0).upper(), match.group(0))

    return _ABBR_RE.sub(_replace, text)
